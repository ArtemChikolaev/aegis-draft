// Общая лестница качества Roguelite Run: тиры, ранги и детерминированный ролл по этапу.
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ. Качество завелось у героев (срез 3b), а теперь его получают и предметы
// (R11.2). Лестница у них ОДНА: те же четыре тира и та же кривая ролла по этапу — иначе «mythic»
// значил бы у героя и у карточки разное, и редкость перестала бы быть единым языком качества.
// Что именно тир ДАЁТ, остаётся знанием каждой сущности: `heroRarity.ts` знает про Hero Synergy и
// цены героя, `items.ts` — про масштаб эффекта карточки.
import { Rng } from "./rng.ts";

export type Rarity = "common" | "unique" | "mythic" | "immortal";

/** По возрастанию качества. Индекс = ранг (0 = common). */
export const RARITIES: readonly Rarity[] = ["common", "unique", "mythic", "immortal"];

export function isRarity(value: string): value is Rarity {
  return (RARITIES as readonly string[]).includes(value);
}

export function rarityRank(r: Rarity): number {
  return RARITIES.indexOf(r);
}

/** Следующий тир вверх, либо null для immortal (потолок). */
export function nextRarity(r: Rarity): Rarity | null {
  return RARITIES[rarityRank(r) + 1] ?? null;
}

/**
 * Кривая качества по этапам (часть `BALANCE_CONFIG_VERSION` — правишь числа, бампай версию).
 *
 * ПОЧЕМУ «ЦЕНТР», А НЕ ЧЕТЫРЕ НЕЗАВИСИМЫХ РАМПЫ (R12.4). Прежние веса были четырьмя линейными
 * рампами со своими потолками (`common: max(4, 74−17s)`, `unique: min(55, 22+8s)` и так далее). Все
 * четыре упирались в потолки уже к ПЯТОМУ этапу, и замер это показал прямо:
 *
 * | этап | standard | refined | exotic | arcana |
 * |------|----------|---------|--------|--------|
 * | 1    | 75%      | 21%     | 3%     | 1%     |
 * | 5    | 6%       | 54%     | 27%    | 13%    |
 * | 6…25 | ~4%      | ~53%    | ~29%   | ~14%   |
 *
 * То есть **20 из 25 этапов сезона имели одно и то же распределение**: лестница качества
 * заканчивалась в первом акте, refined оставался модальным тиром до самого конца, а standard после
 * пятого этапа выпадал так редко, что переставал существовать как контент. Жалоба плейтеста
 * («пассивки выпадали только refined, большего качества ни разу») — прямое следствие: 53% refined
 * против 14% arcana на протяжении всего забега.
 *
 * Теперь у распределения есть ОДИН центр, который едет по лестнице вместе с забегом, а вес тира
 * падает с удалением от центра. Свойства получаются по построению, а не подбором четырёх рамп:
 *  - модальный тир ИДЁТ ВВЕРХ по ходу сезона (standard → refined → exotic), а не стоит на месте;
 *  - у каждого тира ненулевой хвост на любом этапе, то есть требование `R11.4` («редкая сильная
 *    карта обязана иметь шанс выпасть рано») выполняется автоматически, а не отдельным полом;
 *  - в Династии центр останавливается на `maxRank`: качество — КОНЕЧНАЯ ось (там растёт угроза, а не
 *    команда), поэтому arcana не должна становиться модальной.
 *
 * Замер новой кривой: этап 1 — `72/20/6/2`, этап 10 — `25/55/16/5`, этап 18 — `11/37/40/12`,
 * этап 25 — `5/17/61/17`. Модальный тир меняется на refined около этапа 8 и на exotic около 18,
 * насыщение наступает на этапе 23 вместо пятого.
 *
 * Важно про знак `startRank`: центр НИЖЕ нуля бессмысленен. При `center ≤ 0` все веса получают общий
 * множитель `falloff^center`, который сокращается при нормировке, — распределение перестаёт зависеть
 * от центра, и первые этапы стоят на месте (проверено численно). Поэтому `startRank` = 0.
 */
export const RARITY_CURVE = {
  /** Ранг тира, вокруг которого сосредоточена вероятность на первом этапе (0 = common). */
  startRank: 0,
  /** На сколько рангов центр сдвигается за один этап. */
  perStage: 0.09,
  /** Где центр останавливается. Намеренно НЕ 3 (arcana): лестница качества обязана завершаться. */
  maxRank: 2,
  /** Во сколько раз падает вес тира за каждый ранг отдаления от центра. Больше — острее пик.
   *  3.5 подобрано под требование `R11.4`: на первом Буткемпе верхние два тира вместе дают ~7.5%
   *  (у прежней кривой ~4.7%) — редкое определяющее событие, а не запрет и не обыденность. */
  falloff: 3.5,
} as const;

/** Центр распределения качества на этапе (1-based номер этапа Буткемпа). */
function rarityCenter(stageIndex: number): number {
  const step = Math.max(0, Math.floor(stageIndex) - 1);
  return Math.min(RARITY_CURVE.maxRank, RARITY_CURVE.startRank + RARITY_CURVE.perStage * step);
}

/** Веса тиров на этапе. Вес — доля, а не «на сотню»: важны только отношения. */
function rollWeights(stageIndex: number): Record<Rarity, number> {
  const center = rarityCenter(stageIndex);
  const weight = (rarity: Rarity) => RARITY_CURVE.falloff ** -Math.abs(rarityRank(rarity) - center);
  return {
    common: weight("common"),
    unique: weight("unique"),
    mythic: weight("mythic"),
    immortal: weight("immortal"),
  };
}

/** Детерминированный ролл редкости. Один и тот же `(seed, key, stage)` ⇒ тот же тир — поэтому
 *  карточка может показать качество в превью до покупки, а сама покупка выдаст ровно то же.
 *  `key` разводит сущности между собой: `hero-14`, `card-dagon`. */
export function rollRarity(seed: string, key: string, stageIndex: number): Rarity {
  const weights = rollWeights(stageIndex);
  const total = RARITIES.reduce((sum, r) => sum + weights[r], 0);
  const rng = new Rng(`${seed}:rarity:${key}:stage-${stageIndex}`);
  // `rng.float() * total`, а не `rng.int(total)`: веса теперь ДОЛИ (сумма ≈1.5), и целочисленный
  // ролл вырождался бы в «0 или 1». Из потока по-прежнему берётся ровно один float, поэтому
  // длина последовательности сида не меняется.
  let roll = rng.float() * total;
  for (const r of RARITIES) {
    roll -= weights[r];
    if (roll < 0) return r;
  }
  return "common";
}
